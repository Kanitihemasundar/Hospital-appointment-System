<?php
// Start session
// Database connection
$conn = mysqli_connect('localhost', 'root', 'Kaniti@123', 'contact_db') or die('Connection failed');

// Initialize message array
// Initialize message array
$message = [];

// Handle Appointment Form submission
if (isset($_POST['submit'])) {
    $name = mysqli_real_escape_string($conn, $_POST['name']);
    $email = mysqli_real_escape_string($conn, $_POST['email']);
    $number = $_POST['number'];
    $date = $_POST['date'];

    // Insert appointment details into the database
    $insert = mysqli_query($conn, "INSERT INTO contact_form(name, email, number, date) VALUES('$name', '$email', '$number', '$date')") or die('Query failed');

    if ($insert) {
        
        echo '<script>alert("Appointment made successfully!.");</script>';
    } else {
        
        echo '<script>alert("Appointment failed.");</script>';
    }
}
$message = [];

// Handle Login Form submission
// Handle Login Form submission
if (isset($_POST['login'])) {
    $email = mysqli_real_escape_string($conn, $_POST['email']);
    $password = mysqli_real_escape_string($conn, $_POST['password']);

    // Fetch user from database
    $query = mysqli_query($conn, "SELECT * FROM users WHERE email='$email'") or die('Query failed');

    if (mysqli_num_rows($query) > 0) {
        $user = mysqli_fetch_assoc($query);

        // Verify password
        if (password_verify($password, $user['password'])) {
            // Store user info in session variables
          
            $_SESSION['user_name'] = $user['name']; // Store user name in session

            // Redirect to a restricted page (e.g., welcome page) after login
            echo '<script>alert("Login successful!")</script>';
        } else {
            $message[] = 'Incorrect password. Please try again.';
        }
    } else {
        // Pop-up message when no account is found
        echo '<script>alert("No account found with this email. Please sign up.");</script>';
    }
}


// Handle Sign-Up Form submission
if (isset($_POST['signup'])) {
    $name = mysqli_real_escape_string($conn, $_POST['name']);
    $email = mysqli_real_escape_string($conn, $_POST['email']);
    $password = mysqli_real_escape_string($conn, $_POST['password']);

    // Check if email already exists
    $check_email = mysqli_query($conn, "SELECT * FROM users WHERE email='$email'") or die('Query failed');
    if (mysqli_num_rows($check_email) > 0) {
        echo '<script>alert("Email already exists. Please login.");</script>';
    } else {
        // Hash the password for secure storage
        $hashed_password = password_hash($password, PASSWORD_BCRYPT);

        // Insert user data into the database
        $insert = mysqli_query($conn, "INSERT INTO users (name, email, password) VALUES ('$name', '$email', '$hashed_password')") or die('Query failed');

        if ($insert) {
            echo '<script>alert("Sign-Up successful! You can now login.");</script>';
        } else {
            echo '<script>alert("Sign-Up failed. Please try again.");</script>';
        }
    }
}

// Handle logout
if (isset($_GET['logout'])) {
    session_destroy();
    header('Location: index.php');
    exit();
}

